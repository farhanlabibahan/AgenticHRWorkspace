/**
 * Client-safe descriptions of the ATSs Source can import from: what to show
 * on the picker, which credential fields to collect, and where the admin
 * finds them. The adapters themselves live in src/server/imports/providers.
 */

export type CredentialField = {
  key: string;
  label: string;
  kind: 'secret' | 'text' | 'select';
  placeholder?: string;
  help?: string;
  options?: { value: string; label: string }[];
  defaultValue?: string;
  optional?: boolean;
};

export type ProviderMeta = {
  id: string;
  name: string;
  /** For the favicon on the picker. */
  domain: string;
  /** One line under the name. */
  blurb: string;
  /** What comes across, in the order it's imported. */
  imports: string[];
  /** Numbered steps: where the admin creates the key and which permissions it needs. */
  steps: string[];
  docsUrl: string;
  fields: CredentialField[];
  /** Honest caveats shown before starting (API gaps, paid add-ons, expiring links). */
  caveats?: string[];
  /** Importing again updates what changed at the vendor, not only adds what's new (ProviderModule.updatesOnReimport). */
  updatesOnReimport?: boolean;
};

