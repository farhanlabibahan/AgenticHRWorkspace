// Builds src/server/ocr/selftest-fixture.ts from scan-letter.pdf (written by
// make-ocr-fixtures.py), so the deployed OCR self-test reads the same
// scanned document the unit tests do.
//
//   node src/server/ocr/__tests__/fixtures/make-selftest.mjs
//
// The module ships in the OCR cron's bundle only; its size is capped.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const MAX_BASE64 = 40_000;
const base64 = readFileSync(new URL('./scan-letter.pdf', import.meta.url)).toString('base64');
console.log(`scan-letter.pdf ${base64.length} base64 chars`);
if (base64.length > MAX_BASE64) {
  console.error(`Over the ${MAX_BASE64}-character budget: shrink the fixture.`);
  process.exit(1);
}
const out = fileURLToPath(new URL('../../selftest-fixture.ts', import.meta.url));
const lines = base64.match(/.{1,120}/g).map((l) => `  '${l}',`);
writeFileSync(
  out,
  `// Generated by src/server/ocr/__tests__/fixtures/make-selftest.mjs. Do not edit.

/** A fictional resume, scanned: half a letter page, 300 dpi bilevel (CCITT G4), no text layer. */
export const SCANNED_RESUME_PDF = [
${lines.join('\n')}
].join('');
`,
);
console.log(`wrote ${out}`);
