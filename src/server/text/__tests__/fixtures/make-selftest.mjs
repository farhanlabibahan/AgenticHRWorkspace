// Builds src/server/text/selftest-fixtures.ts from the committed fixtures in
// this directory, so the deployed self-test extracts the same synthetic
// documents the unit tests do.
//
//   node src/server/text/__tests__/fixtures/make-selftest.mjs
//
// The generated module ships in the server bundle, so the total is capped.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const MAX_BASE64 = 60_000;

// `expect` must appear in the extracted text: accents catch encoding bugs, and
// the CJK PDF only extracts when pdf.js can read its character maps from disk.
const FIXTURES = [
  { file: 'resume.pdf', format: 'pdf', expect: 'résumé' },
  { file: 'cjk-cmap.pdf', format: 'pdf', expect: '日本語' },
  { file: 'resume.docx', format: 'docx', expect: 'résumé' },
  { file: 'resume.doc', format: 'doc', expect: 'résumé' },
  { file: 'resume.odt', format: 'odt', expect: 'résumé' },
  { file: 'resume.rtf', format: 'rtf', expect: 'résumé' },
  { file: 'resume.txt', format: 'txt', expect: 'résumé' },
];

const here = new URL('./', import.meta.url);
const entries = FIXTURES.map(({ file, format, expect }) => ({
  file,
  format,
  expect,
  base64: readFileSync(new URL(file, here)).toString('base64'),
}));

const total = entries.reduce((sum, e) => sum + e.base64.length, 0);
for (const e of entries) console.log(`${e.file.padEnd(14)} ${String(e.base64.length).padStart(6)} base64 chars`);
console.log(`${'total'.padEnd(14)} ${String(total).padStart(6)}`);
if (total > MAX_BASE64) {
  console.error(`Over the ${MAX_BASE64}-character budget: shrink the fixtures above.`);
  process.exit(1);
}

const body = entries
  .map((e) => `  {\n    format: '${e.format}',\n    base64:\n      '${e.base64}',\n    expect: '${e.expect}',\n  },`)
  .join('\n');
const out = fileURLToPath(new URL('../../selftest-fixtures.ts', here));
writeFileSync(
  out,
  `// Generated by src/server/text/__tests__/fixtures/make-selftest.mjs. Do not edit.
import type { TextFormat } from './types';

export const SELFTEST_FIXTURES: { format: TextFormat; base64: string; expect: string }[] = [
${body}
];
`,
);
console.log(`wrote ${out}`);
